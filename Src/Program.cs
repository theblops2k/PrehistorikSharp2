                    nl.Warp(bex[0].X, bex[0].Y);
                }
            }
            else if (++nextTicks >= 60) break;
        }
    }
    if (reachedLevel >= 0)
    {
        var nl = frunner.ActiveLevel!;
        Console.WriteLine($"next level reached: index {reachedLevel} after {nextTicks} ticks: lives={nl.State.Rb(0x27D8)} energy={nl.State.Rb(0x27D6)} score={nl.State.Rw(0x6C0E)} player=({nl.State.Rw(0x4F1C)},{nl.State.Rw(0x4F1E)}) song={frec.Current}");
        return 0;
    }
    return 1;
}
