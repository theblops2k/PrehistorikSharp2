static int VerifyVga(string refFile)
{
    var refs = new Dictionary<string, string>();
    foreach (string raw in File.ReadLines(refFile))
    {
        string line = raw.Trim();
        int colon = line.IndexOf(':');
        if (line.Length == 0 || colon < 0)
            continue;
        refs[line[..colon]] = line[(colon + 1)..].ToLowerInvariant();
    }

    // Same sequence as work/gen_vga_ref.py (see its docstring).
    var v = new NativeVga();
    void T(int port, int value, int bits) => v.TrackVgaDacPorts(port, value, bits);
    T(0x3C8, 0, 8);
    for (int k = 0; k < 192; k++) T(0x3C9, (k * 7 + 1) & 0xFF, 8);
    T(0x3C8, 250, 8);
    for (int k = 0; k < 24; k++) T(0x3C9, (k * 11 + 5) & 0xFF, 8);
    T(0x3C7, 5, 8);
    T(0x3C8, 60, 8);
    T(0x3C9, 0x11, 8);
    T(0x3C9, 0x22, 8);
    T(0x3C8, 100, 8);
    foreach (int b in new[] { 0x3F, 0x20, 0x01 }) T(0x3C9, b, 8);
    T(0x3C8, 0x3F20, 16);
    T(0x3C9, 0x15, 8);
    T(0x3C9, 0x2A, 8);
    T(0x3C9, 0x12345, 32);
    T(0x3CA, 0x77, 8);
    T(0x3C8, 200, 8);
    T(0x3C9, 0x30, 8);
    T(0x3C7, 9, 8);
    foreach (int b in new[] { 0x0A, 0x14, 0x28 }) T(0x3C9, b, 8);
    T(0x3C8, 7, 8);
    T(0x3C9, 0x3E, 8);
    T(0x3C9, 0x3D, 8);

    var pal = new byte[768];
    for (int i = 0; i < 256; i++)
    {
        pal[i * 3] = v.VgaPalette[i].R;
        pal[i * 3 + 1] = v.VgaPalette[i].G;
        pal[i * 3 + 2] = v.VgaPalette[i].B;
    }

    int pass = 0, fail = 0;
    void Check(string key, string actual)
    {
        bool ok = refs.TryGetValue(key, out string? expected) && expected == actual.ToLowerInvariant();
        string shown = actual.Length > 64 ? actual[..64] + "..." : actual;
        Console.WriteLine($"{(ok ? "PASS" : "FAIL")} {key,-16} {shown}{(ok ? "" : $" (ref {(refs.TryGetValue(key, out string? e) ? (e.Length > 64 ? e[..64] + "..." : e) : "missing")})")}");
        if (ok) pass++; else fail++;
    }
    Check("VIDEO_MODE", v.VideoMode.ToString());
    Check("DAC_WRITE_INDEX", v.DacWriteIndex.ToString());
    Check("DAC_READ_INDEX", v.DacReadIndex.ToString());
    Check("DAC_COMPONENT", v.DacComponent.ToString());
    Check("DAC_LATCH", string.Join(",", v.DacLatch));
    Check("PALETTE_SHA256", Convert.ToHexString(SHA256.HashData(pal)));
    Check("PALETTE_HEX", Convert.ToHexString(pal));

    Console.WriteLine($"\n{pass} passed, {fail} failed");
    return fail == 0 ? 0 : 1;
}

static int VerifyTables(string bootImage, string refFile)
{
    byte[] image = BootImage.Load(bootImage);
    var refs = new Dictionary<string, string>();
    int pass = 0, fail = 0;
    foreach (string raw in File.ReadLines(refFile))
    {
        try
        {
            string line = raw.Trim();
            if (line.Length == 0)
                continue;
            int colon = line.IndexOf(':');
            if (colon < 0)
            {
                Console.WriteLine($"FAIL línea mal formada: {line}");
                fail++;
                continue;
            }
            refs[line[..colon]] = line[(colon + 1)..].ToLowerInvariant();
        }
        catch (Exception ex)
        {
            Console.WriteLine($"FAIL línea mal formada: {ex.Message}");
            fail++;
        }
    }

    void Known(string label, Func<bool> check)
    {
        try
        {
            bool ok = check();
            Console.WriteLine($"{(ok ? "PASS" : "FAIL")} valor conocido {label}");
            if (ok) pass++; else fail++;
        }
        catch (Exception ex)
        {
            Console.WriteLine($"FAIL valor conocido {label}: {ex.GetType().Name}: {ex.Message}");
            fail++;
        }
    }
    Known("COS[1]==1", () => AssetTables.Cos(image)[1] == 1);
    Known("SIN[0]==0x40", () => AssetTables.Sin(image)[0] == 0x40);
    Known("ScoreTable[0]==10", () => AssetTables.ScoreTable(image)[0] == 10);
    Known("ScoreTable[1]==20", () => AssetTables.ScoreTable(image)[1] == 20);
    Known("HurtSfx[0]==0x009B", () => AssetTables.HurtSfx(image)[0] == 0x009B);
    Known("HurtSfx[1]==0x00E0", () => AssetTables.HurtSfx(image)[1] == 0x00E0);

    byte[] hurtRaw = AssetTables.Raw(image, "HURT_SFX");
    for (int n = 0; n <= 12; n++)
    {
        int idx = n;
        Known($"HurtSfxWordAt n={idx}", () => AssetTables.HurtSfxWordAt(image, idx) == (hurtRaw[idx] | hurtRaw[idx + 1] << 8));
    }

    foreach (var (name, offset, length) in AssetTables.Spans)
    {
        try
        {
            byte[] data = AssetTables.Typed(image, name);
            string hex = Convert.ToHexString(data).ToLowerInvariant();
            bool ok = data.Length == length && refs.TryGetValue(name, out string? expected) && hex == expected;
            Console.WriteLine($"{(ok ? "PASS" : "FAIL")} {name,-14} off=0x{offset:X4} len={data.Length,5}");
            if (ok) pass++; else fail++;
        }
        catch (Exception ex)
        {
            Console.WriteLine($"ERR  {name,-14} {ex.GetType().Name}: {ex.Message}");
            fail++;
        }
    }

    Console.WriteLine($"\n{pass} passed, {fail} failed");
    return fail == 0 ? 0 : 1;
}

static int VerifySprites(string bootImage, string originalDir, string refFile)
{
    byte[] image = BootImage.Load(bootImage);
    var refs = new Dictionary<string, string>();
    foreach (string raw in File.ReadLines(refFile))
    {
        string line = raw.Trim();
        int colon = line.IndexOf(':');
        if (line.Length == 0 || colon < 0)
            continue;
        refs[line[..colon]] = line[(colon + 1)..].ToLowerInvariant();
    }

    int pass = 0, fail = 0;
    void Check(string label, string actual)
    {
        // Labels prefixed "SYNTH " are synthetic checks (not the game); the ref key is the label without the prefix.
        string key = label.StartsWith("SYNTH ") ? label["SYNTH ".Length..] : label;
        bool ok = refs.TryGetValue(key, out string? expected) && expected == actual.ToLowerInvariant();
        string shown = label.StartsWith("SYNTH ") ? $"[verificación sintética (no es el juego)] {key}" : label;
        Console.WriteLine($"{(ok ? "PASS" : "FAIL")} {shown,-14} {actual}{(ok ? "" : $" (ref {(refs.TryGetValue(key, out string? e) ? e : "missing")})")}");
        if (ok) pass++; else fail++;
    }
    string Sha(byte[] data) => Convert.ToHexString(SHA256.HashData(data)).ToLowerInvariant();

    try
    {
        var built = SpriteBank.NativeBuild(image, originalDir);
        Check("BANK_SHA256", Sha(built.Bank));
        Check("BANK_LEN", built.Bank.Length.ToString());
        Check("SPRITES_SEG", built.SpritesSeg.ToString());
        Check("NEW_TOP", built.NewTop.ToString());

        // SYNTHETIC verification (NOT THE GAME): SPRITES.SQZ used as a sheet is not a real level sheet. These checks only
        // guard against regressions vs the Python generator and are NOT evidence of equivalence with the original ASM.
        // The real-game equivalence check is VerifyRealSpriteFixture below.
        byte[] decoded = Sqz.Unpack(File.ReadAllBytes(Path.Combine(originalDir, "SPRITES.SQZ")));
        var sheet = SpriteDecode.SpriteSheet.FromBytes(decoded);
        var shared = new SpriteDecode.SharedSpriteBank(built.Bank);
        var res = SpriteClassify.ClassifySprites(SpriteDecode.DecodeSpriteCache(sheet, shared));
        int opaque = 0, empty = 0, partial = 0;
        foreach (byte t in res.Types)
        {
            if (t == SpriteClassify.TypeOpaque) opaque++;
            else if (t == SpriteClassify.TypeEmpty) empty++;
            else partial++;
        }
        Check("SYNTH TYPE_OPAQUE", opaque.ToString());
        Check("SYNTH TYPE_EMPTY", empty.ToString());
        Check("SYNTH PARTIAL", partial.ToString());
        Check("SYNTH TYPES_SHA256", Sha(res.Types));
        Check("SYNTH MASKS_SHA256", Sha(res.Masks[..(res.PartialCount * SpriteDecode.SlotBytes)]));
    }
    catch (Exception ex)
    {
        Console.WriteLine($"ERR  {ex.GetType().Name}: {ex.Message}");
        fail++;
    }

    // REAL-GAME check: ASM witness captured at level load (see tests/test_sprite_decode.py).
    var (rp, rf) = VerifyRealSpriteFixture(@"C:\opencode\Prehistorik2\Sources\pre2_port\tests\fixtures\sprite_decode");
    pass += rp;
    fail += rf;

    Console.WriteLine($"\n{pass} passed, {fail} failed");
    return fail == 0 ? 0 : 1;
}

// Real-game sprite decode check against the ASM witness fixture. Mirrors tests/test_sprite_decode.py:
//  - test_sprite_decode_matches_asm_witness: SHA-256 over cache.slot(slot, plane) for plane 0..3, for each slot of
//    expected["meaningful_slots"] in listed order, compared with expected["asm_meaningful_sha256"].
//  - test_local_and_shared_split: n_local = count(code < 0x100), n_shared = count(code >= 0x100) over meaningful_slots.
//  - test_sentinel_slots_are_left_untouched: all non-meaningful slots stay zero; count == expected["n_sentinel"].
// Additionally the counts are derived independently from the decoded sheet (index table + bank).
static (int Pass, int Fail) VerifyRealSpriteFixture(string fixDir)
{
    int pass = 0, fail = 0;
    void Cmp(string label, string actual, string expected)
    {
        bool ok = actual == expected;
        Console.WriteLine($"{(ok ? "PASS" : "FAIL")} REAL {label,-28} {actual}{(ok ? "" : $" (esperado {expected})")}");
        if (ok) pass++; else fail++;
    }

    try
    {
        var sheet = SpriteDecode.SpriteSheet.FromBytes(File.ReadAllBytes(Path.Combine(fixDir, "local_sheet.bin")));
        var bank = new SpriteDecode.SharedSpriteBank(File.ReadAllBytes(Path.Combine(fixDir, "shared_bank.bin")));
        using var doc = System.Text.Json.JsonDocument.Parse(File.ReadAllText(Path.Combine(fixDir, "expected.json")));
        var root = doc.RootElement;

        var meaningful = new List<(int Slot, int Code)>();
        foreach (var e in root.GetProperty("meaningful_slots").EnumerateArray())
            meaningful.Add((e[0].GetInt32(), e[1].GetInt32()));

        var cache = SpriteDecode.DecodeSpriteCache(sheet, bank);

        // Hash exactly as the Python test: slot order of meaningful_slots, planes 0..3.
        using var sha = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        foreach (var (slot, _) in meaningful)
            for (int plane = 0; plane < 4; plane++)
                sha.AppendData(cache.Slot(slot, plane));
        Cmp("asm_meaningful_sha256", Convert.ToHexString(sha.GetHashAndReset()).ToLowerInvariant(),
            root.GetProperty("asm_meaningful_sha256").GetString()!.ToLowerInvariant());

        // Counts from the fixture's meaningful_slots (as the Python test) ...
        int nLocal = meaningful.Count(m => m.Code < 0x100);
        int nShared = meaningful.Count(m => m.Code >= 0x100);
        Cmp("n_local (fixture)", nLocal.ToString(), root.GetProperty("n_local").GetInt32().ToString());
        Cmp("n_shared (fixture)", nShared.ToString(), root.GetProperty("n_shared").GetInt32().ToString());

        // ... and independently from the decoded sheet's index table + shared bank.
        var set = meaningful.Select(m => m.Slot).ToHashSet();
        int dLocal = 0, dShared = 0, mismatch = 0;
        for (int s = 0; s < sheet.IndexTable.Length; s++)
        {
            int code = sheet.IndexTable[s];
            bool real = code < SpriteDecode.LocalCodeMax || bank.HasSprite(code);
            if (real != set.Contains(s)) mismatch++;
            if (!real) continue;
            if (code < SpriteDecode.LocalCodeMax) dLocal++; else dShared++;
        }
        Cmp("n_local (decoded)", dLocal.ToString(), root.GetProperty("n_local").GetInt32().ToString());
        Cmp("n_shared (decoded)", dShared.ToString(), root.GetProperty("n_shared").GetInt32().ToString());
        Cmp("slots meaningful mismatch", mismatch.ToString(), "0");

        // Sentinel slots untouched (all zero) and their count.
        int untouched = 0, dirty = 0;
        for (int slot = 0; slot < SpriteDecode.NumSlots; slot++)
        {
            if (set.Contains(slot)) continue;
            untouched++;
            for (int plane = 0; plane < 4; plane++)
                if (cache.Slot(slot, plane).Any(b => b != 0)) dirty++;
        }
        Cmp("n_sentinel", untouched.ToString(), root.GetProperty("n_sentinel").GetInt32().ToString());
        Cmp("sentinel planes dirty", dirty.ToString(), "0");

        // ClassifySprites must run on the real cache and be consistent (every slot typed, masks sized by partial count).
        var res = SpriteClassify.ClassifySprites(cache);
        Cmp("classify: types length", res.Types.Length.ToString(), SpriteDecode.NumSlots.ToString());
        int partialSlots = res.Types.Count(t => t >= SpriteClassify.FirstPartialId);
        Cmp("classify: partial count", res.PartialCount.ToString(), partialSlots.ToString());
    }
    catch (Exception ex)
    {
        Console.WriteLine($"ERR  REAL {ex.GetType().Name}: {ex.Message}");
        fail++;
    }
    return (pass, fail);
}

static int VerifySqz(string originalDir, string hashFile)
{
    int pass = 0, fail = 0;
    foreach (string raw in File.ReadLines(hashFile))
    {
        string line = raw.Trim();
        if (line.Length == 0)
            continue;

        string[] parts = line.Split('|');
        string name = parts[0];
        int expectedSize = int.Parse(parts[1]);
        string expectedHash = parts[2];

        try
        {
            byte[] packed = File.ReadAllBytes(Path.Combine(originalDir, name));
            byte[] decoded = Sqz.Unpack(packed);
            string actualHash = Convert.ToHexString(SHA256.HashData(decoded)).ToLowerInvariant();

            bool ok = decoded.Length == expectedSize && actualHash == expectedHash;
            Console.WriteLine($"{(ok ? "PASS" : "FAIL")} {name,-14} size={decoded.Length,6} (ref {expectedSize})");
            if (ok) pass++; else fail++;
        }
        catch (Exception ex)
        {
            Console.WriteLine($"ERR  {name,-14} {ex.GetType().Name}: {ex.Message}");
            fail++;
        }
    }

    Console.WriteLine($"\n{pass} passed, {fail} failed");
    return fail == 0 ? 0 : 1;
}

