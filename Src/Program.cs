// Usage: Pre2Port jumptime <bootImage.bin> <originalDir>  (headless, simulated FrameClock: jump length in LOGIC TICKS at 30/60/144/240 fps render, input latency apart)
if (args.Length == 3 && args[0] == "jumptime")
{
    byte[] jboot = BootImage.Load(args[1]);
    const double jhz = 70.0 / 3.0;
    const double t0 = 21.5 / jhz;   // Up press instant (inside a frame for every rate; after 20 settled ticks)
    var traces = new Dictionary<int, List<(int X, int Y, int Yv)>>();
    var ks = new Dictionary<int, int>();
    foreach (int fps in new[] { 30, 60, 144, 240 })
    {
        var sc = new Pre2Port.Game.Level.LevelScene(jboot, args[2], 0, hud: false, player: true);
        var inp = new Pre2Port.Game.Input();
        var tr = new List<(int, int, int)>();
        int ticks = 0, restY = 0, kConsume = -1, kLand = -1; bool started = false; double tExec = 0;
        for (int f = 0; f < fps * 8 && kLand < 0; f++)
        {
            double now = (double)f / fps;
            bool upVisible = now >= t0;   // key state sampled at frame start, as Presenter does per tick
            long due = Pre2Port.Game.FrameClock.Due(now, 0, jhz, ticks);
            while (due-- > 0 && kLand < 0)
            {
                bool up = upVisible && !started;
                bool first = up && kConsume < 0;
                if (first) { kConsume = ticks; tExec = now; }
                if (ticks == 0 || kConsume < 0) restY = sc.State.Rw(Pre2Port.Native.LevelState.Off.PlayerY);
                inp.Set(Pre2Port.Game.Input.Key.Up, up, first);
                sc.Update(inp); ticks++;
                int yv = (short)sc.State.Rw(Pre2Port.Native.LevelState.Off.PlayerYvel), y = sc.State.Rw(Pre2Port.Native.LevelState.Off.PlayerY);
                tr.Add((sc.State.Rw(Pre2Port.Native.LevelState.Off.PlayerX), y, yv));
                if (kConsume < 0) continue;
                if (!started) { if (yv != 0 || y != restY) started = true; }
                else if (yv == 0 && y == restY) kLand = ticks - 1;
            }
        }
        traces[fps] = tr; ks[fps] = kConsume;
        int jt = kLand - kConsume;
        Console.WriteLine(kLand < 0 ? $"-Salto {fps}: error (no aterriza)" : FormattableString.Invariant($"-Salto {fps}: {jt} ticks = {jt * 3000.0 / 70.0:0.0} Ms (latencia entrada {(tExec - t0) * 1000:0.0} Ms)"));
    }
    Console.WriteLine("-Paso de logica: 42.9 Ms.");
    // Divergence diagnostics (only on mismatch): first tick where (x,y,yvel) differs from the 30 fps run, compared by absolute tick.
    foreach (int fps in new[] { 60, 144, 240 })
    {
        var a = traces[30]; var b = traces[fps]; int n = Math.Min(a.Count, b.Count), i = 0;
        while (i < n && a[i] == b[i]) i++;
        if (i < n) Console.WriteLine($"DIFF {fps} vs 30: tick {i} (K30={ks[30]} K{fps}={ks[fps]}) 30=({a[i].X},{a[i].Y},{a[i].Yv}) {fps}=({b[i].X},{b[i].Y},{b[i].Yv})");
    }
    return 0;
}
