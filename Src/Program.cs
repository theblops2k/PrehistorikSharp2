    for (int t2 = 0; t2 < 6000; t2++, ft++)
    {
        try { frunner.Update(frunner.Phase == "CARTE" && t2 % 9 == 4 ? ffire : fin); frunner.Draw(ffb); }
        catch (Pre2Port.Recovered.ObjectGapException e) { Console.WriteLine($"t={ft}: GAP {e.Message}"); return 0; }
        FNote();
        if (frunner.Phase == "LEVEL" && frunner.ActiveLevel is { } nl && nl.State.Rb(0x2D8A) != curLevel)
        {
            reachedLevel = nl.State.Rb(0x2D8A);
            if (chain && reachedLevel >= 0xA)                                  // a bonus level: play 60 ticks, then leave it through its first 0x117
            {
                if (++nextTicks >= 60)
                {
                    var bex = FFindAll(nl.State, 0x117);
