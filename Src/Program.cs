// Usage: Pre2Port levelflowprobe <bootImage.bin> <originalDir> <levelIndex> [exitN] [chain] [reveal]   (levels without a lighter, e.g. LEVEL7 = 6, go straight to the existing 0x117 exits; "chain" also leaves the bonus level that follows (LEVEL7 -> LEVELG = 15) through its own 0x117 and follows the flow to the tally / CARTE / gap)
