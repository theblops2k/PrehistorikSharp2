    bool chain = fextra.Remove("chain");                                       // chain: when the next level is a bonus level (>= 0xA), also leave it through its exit 0x117 and follow the flow to the tally / CARTE / gap
    int exitN = fextra.Count > 0 ? int.Parse(fextra[0].Replace("exit", "")) : 0;
    var fboot = BootImage.Load(args[1]);
    var frec = new RecordingAudio();
    var frunner = new Pre2Port.Game.Frontend.FrontEndRunner(fboot, args[2], frec);
