    fscene.State.Wb(0x27D8, 4); fscene.State.Ww(0x6C0E, 1234);
    var lighters = FFindAll(fscene.State, 0x63);
    Console.WriteLine($"level {fl} (index): lighters (0x63) {string.Join(" ", lighters)}; exits 0x116 before: {string.Join(" ", FFindAll(fscene.State, 0x116))}; exits 0x117 before: {string.Join(" ", FFindAll(fscene.State, 0x117))}");
