// Usage: Pre2Port gapscan <bootImage.bin> <originalDir> <level>
// Debug: warps the player over the map (x every 96 px, several heights), runs 25 idle ticks each and lists the distinct ObjectGapException messages.
// Usage: Pre2Port fgprobe <bootImage.bin> <originalDir> <level>
// Debug: foreground-tile pass 3721 - level data (flag-0x40 tiles, map cells), then the player is warped next to every such cell and the frame drawn with and without the pass.
if (args.Length == 4 && args[0] == "fgprobe")
{
    int fl = int.Parse(args[3]);
    var fboot = BootImage.Load(args[1]);
    var fsc = new Pre2Port.Game.Level.LevelScene(fboot, args[2], fl, damage: true, bonus: true, platforms: true, attack: true);
    var fs = fsc.State;
    int ftiles = 0; var fset = new List<int>();
    for (int tl = 0; tl < 256; tl++) if ((fs.Rb(0x805E + tl) & 0x40) != 0) { ftiles++; fset.Add(tl); }
    int mapBase = (fs.Rw(0x2DDA) << 4) & Pre2Port.Native.LevelState.AddrMask;
    var cells = new List<int>();
    for (int c = 0; c < 0x10000; c++) if ((fs.Rb(0x805E + fs.Data[mapBase + c]) & 0x40) != 0) cells.Add(c);
    Console.WriteLine($"fgprobe level {fl}: FgBank=[3B]={fs.Rw(0x3B):X4} cs[3]={fs.CsRb(3):X2} [2DF2]={fs.Rb(0x2DF2):X2} flag-0x40 tiles={ftiles} ({string.Join(",", fset.Select(x => x.ToString("X2")))}) map cells={cells.Count}");
    Console.WriteLine("  tile-flag table [0x805E] bit counts (b0..b7 over 256 tiles): " + string.Join(" ", Enumerable.Range(0, 8).Select(b => Enumerable.Range(0, 256).Count(tl => (fs.Rb(0x805E + tl) & (1 << b)) != 0))) + $"  graphic index table [0x8167] nonzero entries={Enumerable.Range(0, 256).Count(tl => fs.Rw(0x8167 + tl * 2) != 0)}");
    Console.WriteLine("  first cells (row,col): " + string.Join(" ", cells.Take(24).Select(c => $"{c >> 8:X2},{c & 0xFF:X2}")));
    int fruns = 0, fwith = 0, fdiff = 0; long fpix = 0, f2df2clear = 0;
    var fin = new Pre2Port.Game.Input(); var fa = new Pre2Port.Game.Framebuffer(); var fb2 = new Pre2Port.Game.Framebuffer();
    var perCell = new List<string>();
    foreach (int cell in cells.Where(c => (c & 0xFF) >= 2 && (c >> 8) >= 2).Where((c, i) => i % Math.Max(1, cells.Count / 400) == 0))
    {
        fruns++;
        fsc.Warp((cell & 0xFF) * 16 + 8, (cell >> 8) * 16 + 16);
        long before = 0;
        try { fsc.Update(fin); fsc.Draw(fa, 1.0); fsc.Warp((cell & 0xFF) * 16 + 8, (cell >> 8) * 16 + 16); before = Pre2Port.Recovered.ForegroundTiles.TilesBlitted; fsc.Draw(fa, 1.0); }   // one tick, then re-place and draw the placed frame (no gravity step in between)
        catch (Exception e) { Console.WriteLine($"  cell {cell:X4}: EXC {e.GetType().Name}: {e.Message}"); continue; }
        long n = Pre2Port.Recovered.ForegroundTiles.TilesBlitted - before;   // blits over the last 3 draws
        bool g = (fsc.State.Rb(0x2DF2) & 0x40) != 0;
        if (!g) f2df2clear++;
        Pre2Port.Recovered.ForegroundTiles.Disabled = true;
        fsc.Draw(fb2, 1.0);
        Pre2Port.Recovered.ForegroundTiles.Disabled = false;
        fsc.Draw(fa, 1.0);
        int d = 0; for (int i = 0; i < fa.Pixels.Length; i++) if (fa.Pixels[i] != fb2.Pixels[i]) d++;
        if (n == 0 && Environment.GetEnvironmentVariable("PRE2_FGDBG") != null && fruns < 40) Console.WriteLine($"  nohit cell {cell:X4}: P=({fsc.State.Rw(0x4F1C):X4},{fsc.State.Rw(0x4F1E):X4}) cam=({fsc.State.Rb(0x2DE4):X2},{fsc.State.Rb(0x2DE6):X2}) fine={fsc.State.Rb(0x6BC4)} sprite={fsc.State.Rw(0x4F20):X4} id={fsc.State.Rw(0x4F20):X4}");
        if (n > 0) fwith++;
        if (d > 0) { fdiff++; fpix += d; }
        if (perCell.Count < 12 && d > 0) perCell.Add($"cell {cell >> 8:X2},{cell & 0xFF:X2}: blits(1 draw)={n} diffPixels={d} [2DF2]&40={(g ? 1 : 0)}");
    }
    Console.WriteLine($"  warps={fruns} withBlits={fwith} framesChanged={fdiff} changedPixels(sum)={fpix} warpsWhere[2DF2]&0x40==0:{f2df2clear}");
    foreach (var l in perCell) Console.WriteLine("  " + l);
    return 0;
}
