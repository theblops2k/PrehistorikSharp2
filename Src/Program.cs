// Usage: Pre2Port fgdump <bootImage.bin> <originalDir> <level> <outDir>   (debug: dumps frames before/after the foreground pass for the Python cross-check work/fg_cross.py)
if (args.Length == 5 && args[0] == "fgdump")
{
    int dl = int.Parse(args[3]);
    var dboot = BootImage.Load(args[1]);
    var dsc = new Pre2Port.Game.Level.LevelScene(dboot, args[2], dl, damage: true, bonus: true, platforms: true, attack: true);
    var din = new Pre2Port.Game.Input();
    Directory.CreateDirectory(args[4]);
    var ds = dsc.State;
    int dmapBase = (ds.Rw(0x2DDA) << 4) & Pre2Port.Native.LevelState.AddrMask;
    var dcells = new List<int>();
    for (int c = 0; c < 0x10000; c++) if ((ds.Rb(0x805E + ds.Data[dmapBase + c]) & 0x40) != 0 && (c & 0xFF) >= 12 && (c >> 8) >= 4) dcells.Add(c);
    int dn = 0;
    foreach (int cell in dcells.Where((c, i) => i % Math.Max(1, dcells.Count / 24) == 0))
    {
        for (int dx = -1; dx <= 1; dx++)
        {
            try { dsc.Update(din); dsc.Warp((cell & 0xFF) * 16 + 8 + dx * 9, (cell >> 8) * 16 + 16 + (dx == 1 ? 5 : 0)); }
            catch (Pre2Port.Recovered.ObjectGapException) { continue; }
            var st = dsc.State;
            if (st.Rw(0x4F20) == 0xFFFF) continue;
            Pre2Port.Recovered.ForegroundTiles.Disabled = true;
            var before = Pre2Port.Recovered.LevelRender.RenderPlanes(st, out int pg, true, true);
            Pre2Port.Recovered.ForegroundTiles.Disabled = false;
            var after = Pre2Port.Recovered.LevelRender.RenderPlanes(st, out int pg2, true, true);
            var drawn = Pre2Port.Recovered.ForegroundTiles.DrawnRecords(st, pg, false);
            int camCol = st.Rb(0x2DE4), camRow = st.Rb(0x2DE6);
            var sel = Pre2Port.Recovered.ForegroundTiles.Select(st, drawn, camCol, camRow).ToList();
            var pxCopy = before.Select(pl => (byte[])pl.Clone()).ToArray();
            Pre2Port.Recovered.ForegroundTiles.ApplyPixels(st, pxCopy, pg, drawn, camCol * 16, camRow * 16 + st.Rb(0x6BC4));
            int pxDiff = 0; for (int pi = 0; pi < 4; pi++) for (int yy = 0; yy < 176; yy++) for (int bb = 0; bb < 40; bb++) { int o = (pg + yy * 40 + bb) & 0xFFFF; if (pxCopy[pi][o] != after[pi][o]) pxDiff++; }
            Console.WriteLine($"  frame {dn:D3}: pixel-path (interpolated image) vs planar pass: {pxDiff} plane bytes differ in the 176 viewport rows");
            string name = $"{dn:D3}";
            File.WriteAllText(Path.Combine(args[4], name + ".txt"),
                "page=" + pg + "\ncamcol=" + camCol + "\ncamrow=" + camRow + "\nfine=" + st.Rb(0x6BC4) + "\nsprites=" + string.Join(";", drawn.Select(d => $"{(short)d.X},{(short)d.Y}")) + "\nsel=" + string.Join(";", sel.Select(x => $"{x.Tile:X2}@{x.Cell:X4}")) + "\n");
            using (var fs2 = File.Create(Path.Combine(args[4], name + ".bin")))
            {
                foreach (var pl in before) fs2.Write(pl, 0, pl.Length);
                foreach (var pl in after) fs2.Write(pl, 0, pl.Length);
                fs2.Write(st.Data, dmapBase, 0x10000);
                fs2.Write(st.Data, Pre2Port.Native.BootImage.DsBase + 0x805E, 256);
                fs2.Write(st.Data, Pre2Port.Native.BootImage.DsBase + 0x8167, 512);
                fs2.Write(st.Data, (st.Rw(0x3B) << 4) & Pre2Port.Native.LevelState.AddrMask, 0x10000);
            }
            dn++;
        }
    }
    Console.WriteLine($"fgdump level {dl}: {dn} frames -> {args[4]}");
    return 0;
}
// Usage: Pre2Port spawnprobe <bootImage.bin> <originalDir> <level>
// Debug: weapon spawn 6017-6073 -> tail 60AE: prints the club record 0x4F0A/0C/0E and the new 0x4F2E slot right after the spawn tick, for weapon phases 2 and 3, facing right and left.
if (args.Length == 4 && args[0] == "spawnprobe")
{
    var sboot = BootImage.Load(args[1]);
    foreach (int phase in new[] { 2, 3 })
        foreach (bool left in new[] { false, true })
        {
            var sc = new Pre2Port.Game.Level.LevelScene(sboot, args[2], int.Parse(args[3]), hud: false, player: true, objects: true, damage: true, bonus: true, platforms: false, attack: true);
            var inp = new Pre2Port.Game.Input();
            sc.State.Wb(0x7B18, phase);
            for (int t = 0; t < 40; t++)
            {
                inp.Set(Pre2Port.Game.Input.Key.Left, left && t < 12, false); inp.Set(Pre2Port.Game.Input.Key.Right, !left && t < 12, false);
                inp.Set(Pre2Port.Game.Input.Key.Space, t >= 14 && t < 17, false);
                sc.Update(inp);
                var st = sc.State;
                if (st.Rw(0x4F32) != 0xFFFF)
                {
                    int px = st.Rw(0x4F1C), py = st.Rw(0x4F1E), xv = (short)st.Rw(0x4F22), yv = (short)st.Rw(0x4F2A), xo = (short)st.Rw(0x4F34), yo = (short)st.Rw(0x4F3C);
                    int slotY = st.Rw(0x4F30), slotSpr = st.Rw(0x4F32);
                    Console.WriteLine($"phase {phase} {(left ? "left " : "right")} tick {t}: P=({px:X4},{py:X4}) xvel={xv:X4} yvel={yv:X4} slot=(x {st.Rw(0x4F2E):X4}, y {slotY:X4}, spr {slotSpr:X4}, xoff {xo & 0xFFFF:X4}, yoff {yo & 0xFFFF:X4}) club=({st.Rw(0x4F0A):X4},{st.Rw(0x4F0C):X4},{st.Rw(0x4F0E):X4})");
                    break;
                }
            }
        }
    return 0;
}
